def write(path: Path, title: str, rows: list[tuple[str, str]], note: str):
    total = sum(secs(t) for _, t in rows)
    lines = [f"# {title}", "", note, "", "| 页 | 主题 | 时长 | 口播 / 字幕 |", "|---|---|---|---|"]
    for i, (topic, text) in enumerate(rows, 1):
        lines.append(f"| {i:02d} | {topic} | {secs(text)}s | {text} |")
    lines += ["", f"合计约 **{total} 秒**（按 3.8 字/秒估算）。", ""]
    lines.append("## 完整口播稿")
    lines.append("")
    lines.append("```")
    for _, text in rows:
        lines.append(text)
        lines.append("")
    lines.append("```")
    path.write_text("\n".join(lines), encoding="utf-8")
    print(path, total, "s")


